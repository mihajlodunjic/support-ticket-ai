CREATE TABLE ticket_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    category VARCHAR(100) NOT NULL,
    probability DOUBLE PRECISION NOT NULL,
    rank INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ticket_predictions_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE CASCADE,
    CONSTRAINT ck_ticket_predictions_probability CHECK (probability >= 0.0 AND probability <= 1.0),
    CONSTRAINT uk_ticket_predictions_ticket_rank UNIQUE (ticket_id, rank)
);

CREATE INDEX idx_ticket_predictions_ticket_id ON ticket_predictions (ticket_id);
